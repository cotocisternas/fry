#!/usr/bin/env python3
"""Prove the active lint policy catches handwritten production and test regressions."""
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
TOOL = ROOT / 'scripts/toolchain.sh'
CONFIG = ROOT / '.golangci.yml'


def lint(directory):
    result = subprocess.run(
        [str(TOOL), 'lint', 'run', '--allow-serial-runners', '--config', str(CONFIG),
         '--output.json.path', str(directory / 'issues.json'),
         '--output.text.path', str(directory / 'issues.txt'), './...'],
        cwd=directory, capture_output=True, text=True, timeout=120)
    assert result.returncode in (0, 1), result.stderr
    report = json.loads((directory / 'issues.json').read_text())
    return result.returncode, report.get('Issues') or []


def source(name, fixed=False):
    receiver = 'r' if fixed else 'different'
    loop = 'for i := range 3 {' if fixed else 'for i := 0; i < 3; i++ {'
    literal = json.dumps('x' * 180)
    if fixed:
        literal = ' +\n'.join(json.dumps('x' * 60) for _ in range(3))
    modern_imports = '"slices"' if fixed else '"sort"'
    cut = 'return bytes.Cut(value, []byte(":"))' if fixed else '''
    if index := bytes.IndexByte(value, ':'); index >= 0 {
        return value[:index], value[index+1:], true
    }
    return value, nil, false'''
    parts = 'for part := range strings.SplitSeq(value, ",")' if fixed else (
        'for _, part := range strings.Split(value, ",")')
    contains = 'return slices.Contains(values, target)' if fixed else '''
    for _, value := range values {
        if value == target {
            return true
        }
    }
    return false'''
    sorting = 'slices.Sort(values)' if fixed else (
        'sort.Slice(values, func(i, j int) bool { return values[i] < values[j] })')
    return f'''package fixture
import (
    "bytes"
    "strings"
    {modern_imports}
)
type {name} struct {{ Value int }}
func (r *{name}) First() int {{ return r.Value }}
func ({receiver} *{name}) Second() int {{ return {receiver}.Value }}
func {name}Loop() int {{
    total := 0
    {loop}
        total += i
    }}
    return total
}}
func {name}Text() string {{ return {literal} }}
func {name}Cut(value []byte) ([]byte, []byte, bool) {{ {cut} }}
func {name}Parts(value string) int {{
    size := 0
    {parts} {{ size += len(part) }}
    return size
}}
func {name}Contains(values []int, target int) bool {{ {contains} }}
func {name}Sort(values []int) {{ {sorting} }}
'''


def main():
    artifacts = ROOT / '.artifacts'
    artifacts.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='lint-policy-', dir=artifacts) as temporary:
        directory = Path(temporary)
        go_version = next(line for line in (ROOT / 'go.mod').read_text().splitlines()
                          if line.startswith('go '))
        (directory / 'go.mod').write_text(f'module fry-lint-policy-fixture\n\n{go_version}\n')
        files = {'handwritten.go': 'Production', 'handwritten_test.go': 'Test'}
        (directory / 'generated.go').write_text(
            '// Code generated by policy fixture. DO NOT EDIT.\n\n' + source('Generated'))
        # Exercise each file kind independently: duplicating the entire fixture
        # in one package would correctly trigger the separate duplication rule.
        for filename, name in files.items():
            fixture = directory / filename
            fixture.write_text(source(name))
            status, issues = lint(directory)
            assert status == 1, 'intentional style violations passed'
            detected = {issue['FromLinter'] for issue in issues
                        if Path(issue['Pos']['Filename']).name == filename}
            assert {'revive', 'lll', 'intrange'} <= detected, (filename, detected, issues)
            modernizers = {issue['Text'].split(':', 1)[0] for issue in issues
                           if issue['FromLinter'] == 'modernize'
                           and Path(issue['Pos']['Filename']).name == filename}
            expected = {'stringscut', 'stringsseq', 'slicescontains', 'slicessort'}
            assert expected <= modernizers, (filename, modernizers, issues)
            assert all(Path(issue['Pos']['Filename']).name != 'generated.go' for issue in issues), issues
            fixture.write_text(source(name, fixed=True))
            subprocess.run([str(TOOL), 'lint', 'fmt', '--config', str(CONFIG), './...'],
                           cwd=directory, check=True, timeout=120)
            status, issues = lint(directory)
            assert status == 0 and not issues, issues
            fixture.unlink()
    print('Lint policy regression passed: style and modernization enforced in production/tests; '
          'generated excluded, fixes accepted.')


if __name__ == '__main__':
    os.environ['PYTHONDONTWRITEBYTECODE'] = '1'
    main()
