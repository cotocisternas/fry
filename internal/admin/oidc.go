type ClaimRule struct {
	Claim  string  `json:"claim"`
	Value  string  `json:"value"`
	Grants []Grant `json:"grants"`
}

// OIDCPolicyConfig contains non-secret installation policy. Transport validates
// provider endpoints and signed tokens; administration owns grant mapping.
type OIDCPolicyConfig struct {
	Issuer, ClientID                      string
	Scopes, SigningAlgorithms             []string
	Rules                                 []ClaimRule
	LoginLifetime, TokenMaxAge, ClockSkew time.Duration
}

// OIDCPolicy is an immutable, generation-bound installation policy. It exposes
// login operations without database queries or transaction access.
type OIDCPolicy struct {
	service    *Service
	config     OIDCPolicyConfig
	generation int64
}

// OIDCLogin carries the consumed browser login's verification material. Its
// private policy binding prevents provisioning an arbitrary generation.
type OIDCLogin struct {
	Nonce, Verifier string
	policy          *OIDCPolicy
}

// ConfigureOIDC applies non-secret provider policy atomically with generation
// invalidation, old claim-grant removal and audit. Local grants stay intact.
func (s *Service) ConfigureOIDC(ctx context.Context, cfg OIDCPolicyConfig) (*OIDCPolicy, error) {
	if err := validateOIDCPolicy(cfg); err != nil {
		return nil, err
	}
	cfg, fingerprint, err := freezeOIDCPolicy(cfg)
	if err != nil {
		return nil, err
	}

	adapter := &OIDCPolicy{service: s, config: cfg}
	tx, err := s.begin(ctx, true)
	if err != nil {
		return nil, err
	}
	defer rollback(ctx, tx)
	if err = updateOIDCPolicy(ctx, tx, fingerprint); err != nil {
		return nil, err
	}
	if adapter.generation, err = dbgen.New(tx).GetConfiguredOIDCGeneration(ctx); err != nil {
		return nil, err
	}
	if err = tx.Commit(ctx); err != nil {
		return nil, err
	}
	return adapter, nil
}

// OIDCLoginStart is browser verification material generated by the transport.
type OIDCLoginStart struct {
	State, BrowserBinding, Nonce, Verifier string
}

// VerifiedOIDCIdentity contains claims whose signature, issuer, audience,
// freshness and browser nonce have been validated by the trusted transport.
type VerifiedOIDCIdentity struct {
	Subject string
	Claims  map[string]json.RawMessage
}

// CreateLogin records browser binding, nonce and PKCE material for one login.
// A stale policy cannot start new logins after configuration changes.
func (o *OIDCPolicy) CreateLogin(ctx context.Context, input OIDCLoginStart) error {
	if len(input.State) != 43 || len(input.BrowserBinding) != 43 || len(input.Nonce) != 43 ||
		len(input.Verifier) != 43 {
		return ErrInvalid
	}
	tx, err := o.service.begin(ctx, false)
	if err != nil {
		return err
	}
	defer rollback(ctx, tx)
	var generation int64
	if generation, err = dbgen.New(tx).GetLoginOIDCGeneration(ctx); err != nil {
		return err
	}
	if generation != o.generation {
		return ErrUnauthorized
	}
	if _, err = dbgen.New(tx).DeleteExpiredOIDCLogins(ctx); err != nil {
		return err
	}
	if _, err = dbgen.New(tx).
		CreateOIDCLogin(
			ctx,
			dbgen.CreateOIDCLoginParams{
				StateHash:       digest(input.State),
				BrowserHash:     digest(input.BrowserBinding),
				Nonce:           input.Nonce,
				Verifier:        input.Verifier,
				Generation:      generation,
				LifetimeSeconds: int64(o.config.LoginLifetime / time.Second),
			},
		); err != nil {
		return err
	}
	return tx.Commit(ctx)
}

// ConsumeLogin consumes state before provider exchange, including error callbacks.
// A wrong browser does not consume another browser's state.
func (o *OIDCPolicy) ConsumeLogin(ctx context.Context, state, binding string) (OIDCLogin, error) {
	var none OIDCLogin
	if len(state) != 43 || len(binding) != 43 {
		return none, ErrUnauthorized
	}
	login, err := dbgen.New(o.service.db).
		ConsumeOIDCLogin(ctx, dbgen.ConsumeOIDCLoginParams{StateHash: digest(state), BrowserHash: digest(binding)})
	if errors.Is(err, pgx.ErrNoRows) {
		return none, ErrUnauthorized
	}
	if err != nil {
		return none, err
	}
	if login.Generation != o.generation {
		return none, ErrUnauthorized
	}
	return OIDCLogin{Nonce: login.Nonce, Verifier: login.Verifier, policy: o}, nil
}

// CompleteLogin accepts claims only after transport signature, issuer, audience,
// freshness and nonce validation. Mapping, user enablement, generation checks,
// grant reconciliation, session issuance and audit share one transaction.
func (o *OIDCPolicy) CompleteLogin(
	ctx context.Context,
	login OIDCLogin,
	identity VerifiedOIDCIdentity,
) (Session, error) {
	if login.policy != o || identity.Subject == "" || len(identity.Subject) > 1024 {
		return Session{}, ErrUnauthorized
	}
	mapped, err := o.mapClaims(identity.Claims)
	if err != nil {
		return Session{}, err
	}
	return o.provision(ctx, identity.Subject, o.generation, mapped)
}

func (o *OIDCPolicy) mapClaims(claims map[string]json.RawMessage) ([]Grant, error) {
	matched := map[string]bool{}
	for _, rule := range o.config.Rules {
		raw, exists := claims[rule.Claim]
		if !exists {
			continue
		}
		values, err := claimValues(raw)
		if err != nil {
			return nil, err
		}
		if slices.Contains(values, rule.Value) {
			for _, grant := range rule.Grants {
				matched[grant.Scope] = matched[grant.Scope] || grant.Content
			}
		}
	}
	return mappedClaimGrants(matched), nil
}

func claimValues(raw json.RawMessage) ([]string, error) {
	if len(raw) > 64<<10 {
		return nil, ErrUnauthorized
	}
	var decoded any
	if json.Unmarshal(raw, &decoded) != nil {
		return nil, ErrUnauthorized
	}
	var values []string
	switch value := decoded.(type) {
	case string:
		values = []string{value}
	case []any:
		var err error
		values, err = claimStringList(value)
		if err != nil {
			return nil, err
		}
	default:
		return nil, ErrUnauthorized
	}
	for _, value := range values {
		if len(value) > 4096 {
			return nil, ErrUnauthorized
		}
	}
	return values, nil
}

func claimStringList(values []any) ([]string, error) {
	if len(values) > 1024 {
		return nil, ErrUnauthorized
	}
	result := make([]string, 0, len(values))
	for _, value := range values {
		text, ok := value.(string)
		if !ok {
			return nil, ErrUnauthorized
		}
		result = append(result, text)
	}
	return result, nil
}

func mappedClaimGrants(matched map[string]bool) []Grant {
	scopes := make([]string, 0, len(matched))
	for scope := range matched {
		scopes = append(scopes, scope)
	}
	sort.Strings(scopes)
	result := make([]Grant, 0, len(scopes))
	for _, scope := range scopes {
		result = append(result, Grant{Scope: scope, Content: matched[scope], Source: "oidc"})
	}
	return result
}

func (o *OIDCPolicy) provision(ctx context.Context, subject string, generation int64, mapped []Grant) (Session, error) {
	var result Session
	tx, err := o.service.begin(ctx, true)
	if err != nil {
		return result, err
	}
	defer rollback(ctx, tx)
	var current int64
	if current, err = dbgen.New(tx).GetProvisionOIDCGeneration(ctx); err != nil {
		return result, err
	}
	if current != generation {
		return result, ErrUnauthorized
	}
	id, err := o.provisionUser(ctx, tx, subject)
	if err != nil {
		return result, err
	}
	if err = o.reconcileOIDCGrants(ctx, tx, id, mapped); err != nil {
		return result, err
	}
	// Commit removed grants even if the user no longer has any access. Rolling
	// back on that denial would preserve their old grants and existing sessions.
	access, err := grants(ctx, tx, id)
	if err != nil {
		return result, err
	}
	if err = audit(ctx, tx, id, "oidc-grants-reconcile", "", id); err != nil {
		return result, err
	}
	return o.completeProvision(ctx, tx, id, generation, access)
}

// DisableOIDC invalidates external sessions when installation configuration
// removes the provider. Repeated local-only starts do not change generations.
func (s *Service) DisableOIDC(ctx context.Context) error {
	tx, err := s.begin(ctx, true)
	if err != nil {
		return err
	}
	defer rollback(ctx, tx)
	var fingerprint string
	if fingerprint, err = dbgen.New(tx).GetDisabledOIDCFingerprint(ctx); err != nil {
		return err
	}
	if fingerprint == "" {
		return nil
	}
	if _, err = dbgen.New(tx).ClearOIDCFingerprint(ctx); err != nil {
		return err
	}
	if _, err = dbgen.New(tx).DeleteDisabledOIDCGrants(ctx); err != nil {
		return err
	}
	if err = audit(ctx, tx, "configuration", "oidc-disable", "", ""); err != nil {
		return err
	}
	return tx.Commit(ctx)
}

func validateOIDCPolicy(cfg OIDCPolicyConfig) error {
	if cfg.Issuer == "" || len(cfg.ClientID) == 0 || len(cfg.ClientID) > 1024 || !validOIDCPolicyTime(cfg) ||
		len(cfg.Rules) > 256 ||
		len(cfg.SigningAlgorithms) == 0 {
		return ErrInvalid
	}
	for _, rule := range cfg.Rules {
		if err := validateClaimRule(rule); err != nil {
			return err
		}
	}
	return nil
}

func validOIDCPolicyTime(cfg OIDCPolicyConfig) bool {
	return cfg.LoginLifetime >= time.Minute && cfg.LoginLifetime <= 10*time.Minute && cfg.TokenMaxAge >= time.Minute &&
		cfg.TokenMaxAge <= 15*time.Minute &&
		cfg.ClockSkew >= 0 &&
		cfg.ClockSkew <= time.Minute
}

func validateClaimRule(rule ClaimRule) error {
	if rule.Claim == "" || len(rule.Claim) > 128 || rule.Value == "" || len(rule.Value) > 1024 ||
		len(rule.Grants) == 0 ||
		len(rule.Grants) > 256 {
		return ErrInvalid
	}
	for _, grant := range rule.Grants {
		if grant.Scope != "*" && !validID(grant.Scope) {
			return ErrInvalid
		}
	}
	return nil
}

func freezeOIDCPolicy(cfg OIDCPolicyConfig) (OIDCPolicyConfig, string, error) {
	// Freeze caller-owned slices and rule grants, without persisting client secrets.
	frozen, err := json.Marshal(struct {
		Issuer, ClientID   string
		Scopes, Algorithms []string
		Rules              []ClaimRule
		Login, Age, Skew   time.Duration
	}{
		cfg.Issuer,
		cfg.ClientID,
		cfg.Scopes,
		cfg.SigningAlgorithms,
		cfg.Rules,
		cfg.LoginLifetime,
		cfg.TokenMaxAge,
		cfg.ClockSkew,
	})
	if err != nil {
		return cfg, "", err
	}
	sum := sha256.Sum256(frozen)
	fingerprint := hex.EncodeToString(sum[:])
	rules := append([]ClaimRule(nil), cfg.Rules...)
	for i := range rules {
		rules[i].Grants = append([]Grant(nil), rules[i].Grants...)
	}
	cfg.Rules = rules
	cfg.Scopes = append([]string(nil), cfg.Scopes...)
	cfg.SigningAlgorithms = append([]string(nil), cfg.SigningAlgorithms...)

	return cfg, fingerprint, nil
}

func (o *OIDCPolicy) provisionUser(ctx context.Context, tx pgx.Tx, subject string) (string, error) {
	id, err := identifier()
	if err != nil {
		return "", err
	}
	var enabled bool
	userRow, err := dbgen.New(tx).
		UpsertOIDCUser(ctx, dbgen.UpsertOIDCUserParams{ID: id, Issuer: &o.config.Issuer, Subject: &subject})
	if err == nil {
		id = userRow.ID
		enabled = userRow.Enabled
	}
	if err != nil {
		return "", err
	}
	if !enabled {
		return "", ErrUnauthorized
	}
	return id, nil
}

func (o *OIDCPolicy) reconcileOIDCGrants(ctx context.Context, tx pgx.Tx, id string, mapped []Grant) error {
	var err error
	if _, err = dbgen.New(tx).DeleteUserOIDCGrants(ctx, id); err != nil {
		return err
	}
	for _, g := range mapped {
		if g.Scope != "*" {
			var exists bool
			if exists, err = dbgen.New(tx).OrganizationExistsForOIDCGrant(ctx, g.Scope); err != nil {
				return err
			}
			if !exists {
				return ErrInvalid
			}
		}
		if _, err = dbgen.New(tx).
			CreateOIDCGrant(
				ctx,
				dbgen.CreateOIDCGrantParams{UserID: id, Scope: g.Scope, Content: g.Content},
			); err != nil {
			return err
		}
	}
	return nil
}

// completeProvision is the terminal step of provision's exclusive policy transaction.
// Empty access must commit removed grants and revoked sessions before returning denial.
func (o *OIDCPolicy) completeProvision(
	ctx context.Context,
	tx pgx.Tx,
	id string,
	generation int64,
	access []Grant,
) (Session, error) {
	var result Session
	var err error
	if len(access) == 0 {
		if _, err = dbgen.New(tx).DeleteUserSessions(ctx, id); err != nil {
			return result, err
		}
		if err = tx.Commit(ctx); err != nil {
			return result, err
		}
		return result, ErrForbidden
	}
	result, err = o.service.issue(ctx, tx, id, "oidc", &generation)
	if err != nil {
		return result, err
	}
	if err = audit(ctx, tx, id, "login-oidc", "", id); err != nil {
		return result, err
	}
	return result, tx.Commit(ctx)
}

func updateOIDCPolicy(ctx context.Context, tx pgx.Tx, fingerprint string) error {
	var err error
	var prior string
	if prior, err = dbgen.New(tx).GetOIDCFingerprint(ctx); err != nil {
		return err
	}
	if prior != fingerprint {
		if _, err = dbgen.New(tx).UpdateOIDCFingerprint(ctx, fingerprint); err != nil {
			return err
		}
		// Old claim grants must not confer access through a later local grant change.
		if _, err = dbgen.New(tx).DeleteAllOIDCGrants(ctx); err != nil {
			return err
		}
		if err = audit(ctx, tx, "configuration", "oidc-policy-update", "", fingerprint); err != nil {
			return err
		}
	}
	return nil
}
